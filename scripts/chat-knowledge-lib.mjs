// Shared by scripts/chat-knowledge.mjs (writes the file) and tests/chat-knowledge.test.mjs (checks it).
import { renderHtml } from '../tests/helpers/render.mjs';

/** The pages whose text the chat may answer from: route and source file. */
export const KNOWLEDGE_PAGES = [
  ['/', 'app/[locale]/page.tsx'],
  ['/autizmus', 'app/[locale]/autizmus/page.tsx'],
  ['/segitseg', 'app/[locale]/segitseg/page.tsx'],
  ['/rolunk', 'app/[locale]/rolunk/page.tsx'],
  ['/rolunk-irtak', 'app/[locale]/rolunk-irtak/page.tsx'],
  ['/tamogatas', 'app/[locale]/tamogatas/page.tsx'],
  ['/dokumentumok', 'app/[locale]/dokumentumok/page.tsx'],
  ['/kapcsolat', 'app/[locale]/kapcsolat/page.tsx'],
];

const ENTITIES = { '&amp;': '&', '&quot;': '"', '&#x27;': "'", '&lt;': '<', '&gt;': '>', '&nbsp;': ' ' };

/** Rendered HTML to plain text that keeps the page's structure: headings, paragraphs, list items. */
export function htmlToKnowledgeText(html) {
  const lines = html
    .replace(/<(script|style|svg|form)[\s\S]*?<\/\1>/g, ' ')
    .replace(/<h[1-6][^>]*>/g, '\n## ')
    .replace(/<li[^>]*>/g, '\n- ')
    .replace(/<\/(h[1-6]|p|li|div|section|tr|dt|dd|blockquote)>|<br\s*\/?>/g, '\n')
    .replace(/<[^>]+>/g, ' ')
    .replace(/&(amp|quot|#x27|lt|gt|nbsp);/g, (m) => ENTITIES[m])
    .split('\n')
    .map((l) => l.replace(/\s+/g, ' ').trim())
    .filter((l) => l && l !== '-' && l !== '##');
  // a line repeated right after itself (e.g. a desktop and a mobile copy of one block) only once
  return lines.filter((l, i) => l !== lines[i - 1]).join('\n');
}

export async function knowledgeFromPages(pages) {
  const out = [];
  for (const [route, file] of pages) out.push({ route, text: htmlToKnowledgeText(await renderHtml(file)) });
  return out;
}

export function renderKnowledgeModule(pages) {
  return [
    '// GENERATED by scripts/chat-knowledge.mjs from the rendered pages. Do not edit by hand:',
    '// change the page, then run `npm run chat:knowledge`. tests/chat-knowledge.test.mjs checks it.',
    '',
    'export interface KnowledgePage {',
    '  route: string;',
    '  text: string;',
    '}',
    '',
    `export const SITE_KNOWLEDGE: KnowledgePage[] = ${JSON.stringify(pages, null, 2)};`,
    '',
  ].join('\n');
}
